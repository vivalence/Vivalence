"""appendix3 — appendix III of the quest: milestone 7 (a render is turns in, a turn out).

    python3 appendix3.py <tree> <after-7> <registry> <registry-after-7>   → appendix III on stdout

The tree section's paths are relative to the tree, the registry section's to ~/.viva/registry.
"""
import filecmp, os, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
tree, after, registry, moved = [stage.rstrip("/") for stage in sys.argv[1:5]]
SKIP = {"node_modules", "snapshots", ".git", ".jj", ".ikiro", "bak"}


def edited(old, new, roots):
    paths = []
    for root in roots:
        for folder, folders, files in os.walk(os.path.join(new, root)):
            folders[:] = sorted(name for name in folders if name not in SKIP)
            for name in sorted(files):
                if os.path.islink(os.path.join(folder, name)) or name.startswith(".#"): continue
                path = os.path.relpath(os.path.join(folder, name), new)
                twin = os.path.join(old, path)
                if os.path.exists(twin) and not filecmp.cmp(twin, os.path.join(new, path), shallow=False):
                    paths.append(path)
    return paths


def section(heading, old, new, roots):
    paths = edited(old, new, roots)
    run = subprocess.run(
        ["python3", os.path.join(here, "todiffs.py"), old, new, *paths],
        capture_output=True, text=True, check=True,
    )
    print(f"{heading}\n\n{len(paths)} files edited.\n\n{run.stdout}", end="")


print("""#+title: channel media — appendix III: the diffs of milestone 7
#+status: replayed on fresh copies; suites read after
# writer: agent · limit: 60000 chars · generated by .ikiro/reference/channel-media/appendix3.py, never by hand

Milestone 7 lands on a copy of the tree that holds 1 – 6, its registry half on a copy of the registry:

#+begin_src sh
sh .ikiro/reference/channel-media/replay.sh <copy> 7
sh .ikiro/reference/channel-media/replay.sh <registry copy> 7r
#+end_src
""")
section("* milestone 7 — a render is turns in, a turn out", tree, after, ["subsystems", "systems", "commons"])
section("* milestone 7 — the registry caller follows", registry, moved, ["education/modes/tactics/harvest"])

"""appendix2 — appendix II of the quest: milestone 5 (the registry fixtures) and milestone 6 (packets).

    python3 appendix2.py <registry-before> <registry-after> <after-4b> <after-6>   → appendix II on stdout

Milestone 5's paths are relative to the registry root (~/.viva/registry); milestone 6's to the tree.
"""
import filecmp, os, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
registry, moved, before, after = [stage.rstrip("/") for stage in sys.argv[1:5]]
SKIP = {"node_modules", "snapshots", ".git", ".jj", ".ikiro", "bak"}


def edited(old, new, roots):
    paths = []
    for root in roots:
        for folder, folders, files in os.walk(os.path.join(new, root)):
            folders[:] = sorted(name for name in folders if name not in SKIP)
            for name in sorted(files):
                if os.path.islink(os.path.join(folder, name)): continue
                path = os.path.relpath(os.path.join(folder, name), new)
                twin = os.path.join(old, path)
                if os.path.exists(twin) and not filecmp.cmp(twin, os.path.join(new, path), shallow=False):
                    paths.append(path)
    return paths


def section(heading, old, new, roots):
    paths = edited(old, new, roots)
    run = subprocess.run(
        ["python3", os.path.join(here, "todiffs.py"), old, new, *paths],
        capture_output=True, text=True, check=True,
    )
    print(f"{heading}\n\n{len(paths)} files edited.\n\n{run.stdout}", end="")


print("""#+title: channel media — appendix II: the diffs of milestones 5 · 6
#+status: replayed on fresh copies; suites read after each
# writer: agent · limit: 40000 chars · generated by .ikiro/reference/channel-media/appendix2.py, never by hand

Milestone 5 lands on a copy of the registry, milestone 6 on a copy of the tree that holds 1 – 4b:

#+begin_src sh
sh .ikiro/reference/channel-media/replay.sh <registry copy> 5
sh .ikiro/reference/channel-media/replay.sh <copy> 6
#+end_src
""")
section("* milestone 5 — the registry fixtures follow", registry, moved, ["assembly", "vcompany"])
section("* milestone 6 — a packet carries its media type", before, after, ["subsystems", "systems", "commons"])

"""appendix — the quest's diff appendix, written from five staged copies.

    python3 appendix.py <pristine> <after-1> <after-2> <after-3> <after-4b>   → the appendix on stdout

Each section is the difference between two neighbouring stages (todiffs.py); a file new in a stage
is shown whole and copied to new/<path>, which replay.sh lands.
"""
import filecmp, os, shutil, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
stages = [stage.rstrip("/") for stage in sys.argv[1:6]]
SKIP = {"node_modules", "snapshots", ".git", ".jj", ".ikiro", "bak"}
ROOTS = ["subsystems", "systems", "commons"]


def changed(before, after):
    edited, born = [], []
    for root in ROOTS:
        for folder, folders, files in os.walk(os.path.join(after, root)):
            folders[:] = sorted(name for name in folders if name not in SKIP)
            for name in sorted(files):
                if os.path.islink(os.path.join(folder, name)): continue
                path = os.path.relpath(os.path.join(folder, name), after)
                old = os.path.join(before, path)
                if not os.path.exists(old): born.append(path)
                elif not filecmp.cmp(old, os.path.join(after, path), shallow=False): edited.append(path)
    return edited, born


def diffs(before, after, paths):
    if not paths: return ""
    run = subprocess.run(
        ["python3", os.path.join(here, "todiffs.py"), before, after, *paths],
        capture_output=True, text=True, check=True,
    )
    return run.stdout


def whole(after, path):
    target = os.path.join(here, "new", path)
    os.makedirs(os.path.dirname(target), exist_ok=True)
    shutil.copyfile(os.path.join(after, path), target)
    body = open(os.path.join(after, path), encoding="utf-8").read().rstrip()
    return f"#+begin_src js\n// {path}\n{body}\n#+end_src\n\n"


HEADINGS = [
    "* milestone 1 — the grammar",
    "* milestone 2 — match · lower · take · give",
    "* milestones 3 · 4 — held in, held out",
    "* milestone 4b — filing on every route that passes turns",
]

shutil.rmtree(os.path.join(here, "new"), ignore_errors=True)
print("""#+title: channel media — appendix I: the diffs of milestones 1 · 2 · 3 · 4 · 4b
#+status: replayed on a fresh copy, section by section; suites read after each
# writer: agent · limit: 160000 chars · generated by .ikiro/reference/channel-media/appendix.py from five staged copies, never by hand

Replay, one section at a time, on a copy:

#+begin_src sh
sh .ikiro/reference/channel-media/replay.sh <copy>
#+end_src
""")
for step, heading in enumerate(HEADINGS):
    before, after = stages[step], stages[step + 1]
    edited, born = changed(before, after)
    print(heading + "\n")
    print(f"{len(edited)} files edited, {len(born)} new.", end="")
    if born: print(" The new ones, whole; they live at =.ikiro/reference/channel-media/new/<path>= until they land.", end="")
    print("\n")
    for path in born: print(whole(after, path), end="")
    print(diffs(before, after, edited), end="")

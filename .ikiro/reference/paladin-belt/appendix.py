"""appendix — the paladin belt quest's diff appendix, written from staged copies.

    python3 appendix.py <pristine> <staged> <pristine registry> <staged registry>   → org on stdout

A file that is new, or a belt file rewritten whole, is shown whole and copied to new/<path>, which
replay.sh lands. Every other changed file is diff blocks (channel-media/todiffs.py).
"""
import filecmp, os, shutil, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
todiffs = os.path.join(here, "../channel-media/todiffs.py")
pristine, staged, registry, registered = (path.rstrip("/") for path in sys.argv[1:5])
SKIP = {"node_modules", "snapshots", ".git", ".jj", ".ikiro", "bak", "dist", ".svelte-kit", ".astro"}
BELT = "subsystems/paladin/gestalten/belt/"
SECTIONS = [
    ("* paladin", ["subsystems/paladin"]),
    ("* runtime · ghost · anima", ["systems"]),
    ("* commons", ["commons"]),
    ("* testament", ["testament"]),
    ("* documentation", ["documentation"]),
]


def walk(root, top):
    for folder, folders, files in os.walk(os.path.join(root, top)):
        folders[:] = sorted(name for name in folders if name not in SKIP)
        for name in sorted(files):
            full = os.path.join(folder, name)
            if not os.path.islink(full):
                yield os.path.relpath(full, root)


def changed(before, after, tops):
    edited, born, gone = [], [], []
    for top in tops:
        if not os.path.isdir(os.path.join(after, top)):
            continue
        for path in walk(after, top):
            old = os.path.join(before, path)
            if not os.path.exists(old):
                born.append(path)
            elif not filecmp.cmp(old, os.path.join(after, path), shallow=False):
                edited.append(path)
        gone += [path for path in walk(before, top) if not os.path.exists(os.path.join(after, path))]
    return edited, born, gone


def diffs(before, after, paths):
    if not paths:
        return ""
    run = subprocess.run(
        ["python3", todiffs, before, after, *paths], capture_output=True, text=True, check=True
    )
    return run.stdout


def whole(after, path):
    target = os.path.join(here, "new", path)
    os.makedirs(os.path.dirname(target), exist_ok=True)
    shutil.copyfile(os.path.join(after, path), target)
    body = open(os.path.join(after, path), encoding="utf-8").read().rstrip()
    return f"#+begin_src js\n// {path}\n{body}\n#+end_src\n\n"


shutil.rmtree(os.path.join(here, "new"), ignore_errors=True)
print("""#+title: paladin belt — appendix I: the diffs of the whole blast radius
#+status: generated from a staged copy; replayed on a fresh copy and compared file by file
# writer: agent · limit: 400000 chars · generated by .ikiro/reference/paladin-belt/appendix.py, never by hand

Replay on a copy of the tree and a copy of =~/.viva/registry=, never on either itself:

#+begin_src sh
sh .ikiro/reference/paladin-belt/replay.sh <copy of the tree> <copy of the registry>
#+end_src
""")

manifest = {"whole": [], "gone": []}
for heading, tops in SECTIONS:
    edited, born, gone = changed(pristine, staged, tops)
    rewritten = [path for path in edited if path.startswith(BELT)]
    patched = [path for path in edited if not path.startswith(BELT)]
    print(heading + "\n")
    print(f"{len(patched)} files edited, {len(rewritten)} rewritten whole, {len(born)} new, {len(gone)} removed.\n")
    if gone:
        print("Removed:\n\n#+begin_src text\n" + "\n".join(gone) + "\n#+end_src\n")
    for path in born + rewritten:
        print(whole(staged, path), end="")
    manifest["whole"] += born + rewritten
    manifest["gone"] += gone
    print(diffs(pristine, staged, patched), end="")

edited, born, gone = changed(registry, registered, sorted(os.listdir(registered)))
print("* the registry packages\n")
print(f"{len(edited)} files edited, {len(born)} new, {len(gone)} removed. Paths start at =~/.viva/registry/=.\n")
print(diffs(registry, registered, edited), end="")

with open(os.path.join(here, "manifest.txt"), "w", encoding="utf-8") as out:
    out.write("".join(f"whole {path}\n" for path in manifest["whole"]))
    out.write("".join(f"gone {path}\n" for path in manifest["gone"]))
